// The scripted transcript. One []step drives both cores in turn, against one
// fake server each. Everything a scenario needs is expressible as four steps,
// and none of them mentions either core: that is what makes the two runs
// comparable at all.

type stepKind int

const (
	stepSend  stepKind = iota // server sends these lines, then a barrier
	stepWait                  // the client must send a line matching this pattern
	stepAct                   // the user does something, then a barrier
	stepReply                 // send lines, but only if the client asked first
	stepDrop                  // the server drops the connection and waits for a redial
)

// step is one transcript entry. See send/wait/act/replyTo/drop below.
type step struct {
	kind  stepKind
	lines []string
	pat   string
	act   action
}

// send is a group: the server writes these lines and both cores are then
// synchronised, so everything they produced is attributed to this one step.
// Grouping several lines is how a BATCH is compared — v1 delivers its contents
// one line at a time and v2 delivers them at the close, and putting the whole
// batch in one group is what lets the two be the same facts.
func send(lines ...string) step { return step{kind: stepSend, lines: lines} }

// wait asserts the client sent a line matching pattern and consumes it. The
// matched line is remembered, so a later send can echo its label back with
// %LABEL% — the label is generated by the core under test and cannot be
// hardcoded in a transcript that drives both.
func wait(pattern string) step { return step{kind: stepWait, pat: pattern} }

// act performs a user action and then synchronises.
func act(a action) step { return step{kind: stepAct, act: a} }

// replyTo sends lines only when the client has already asked for something
// matching pattern — a real server answers what it is asked, and the two cores
// do not ask for the same things (v1 answers every MODE with a NAMES refresh;
// v2 parses the delta). An unconditional reply would paper over that.
func replyTo(pattern string, lines ...string) step {
	return step{kind: stepReply, pat: pattern, lines: lines}
}

// drop closes the connection server-side and waits for the client to redial and
// re-register.
func drop() step { return step{kind: stepDrop} }

// action is something the user did. Each core maps it onto its own API; that
// mapping is the whole of what M7's adapter has to get right, which is why the
// harness spells it out rather than reaching into either core's internals.
type action struct {
	kind   string
	target string
	text   string
}

const (
	actJoin   = "join"
	actPart   = "part"
	actCycle  = "cycle"
	actSay    = "say"
	actMe     = "me"
	actClose  = "close"
	actIgnore = "ignore"
)

func join(ch string) action          { return action{kind: actJoin, target: ch} }
func part(ch string) action          { return action{kind: actPart, target: ch} }
func cycle(ch string) action         { return action{kind: actCycle, target: ch} }
func say(buf, text string) action    { return action{kind: actSay, target: buf, text: text} }
func me(buf, text string) action     { return action{kind: actMe, target: buf, text: text} }
func closeBuffer(name string) action { return action{kind: actClose, target: name} }
func ignoreNick(nick string) action  { return action{kind: actIgnore, target: nick} }

func (a action) String() string {
	if a.text != "" {
		return fmt.Sprintf("%s %s %q", a.kind, a.target, a.text)
	}
	return strings.TrimSpace(a.kind + " " + a.target)
}

// nick is the nick both cores register under.
const nick = "eco"

// --- the cores ----------------------------------------------------------------

// core is one implementation under test. The harness never learns which one it
// is holding, so neither run can be special-cased.
type core interface {
	// start connects and registers, returning once the core reports ready.
	start(t *testing.T)
	// server is the fake server this core is talking to.
	server() *testsrv.Server
	// do performs a user action.
	do(t *testing.T, a action)
	// settle folds everything the server has already delivered.
	settle(t *testing.T)
	// take returns the facts recorded since the last take, normalised.
	take() []Fact
	// snapshot is the final state of every buffer.
	snapshot() []bufferSnap
	// stop tears the core down.
	stop(t *testing.T)
}

// group is one transcript step's worth of facts.
type group struct {
	label string
	facts []Fact
}

// coreRun is everything one core produced.
type coreRun struct {
	groups []group
	state  []bufferSnap
}

// bufferSnap is one buffer's final state.
type bufferSnap struct {
	Name    string
	Topic   string
	Modes   string
	Key     string
	Members []string // "nick(@+)", sorted by folded nick
	Lines   []Fact   // in order, never sorted: this is the log
}

func (b bufferSnap) header() string {
	return fmt.Sprintf("%s topic=%q modes=%q key=%q members=%v",
		b.Name, b.Topic, b.Modes, b.Key, b.Members)
}

// --- the runner ---------------------------------------------------------------

// runCore drives one core through the transcript.
func runCore(t *testing.T, c core, steps []step) coreRun {
	t.Helper()
	srv := c.server()
	run := coreRun{}
	// rosters is this core's "what is on screen" memory, threaded through every
	// take so a roster the user is already looking at is not re-reported.
	rosters := map[string]string{}
	take := func() []Fact { return collapseRosters(c.take(), rosters) }
	add := func(label string) {
		run.groups = append(run.groups, group{label: label, facts: sortFacts(take())})
	}
	// barrier is the synchronisation the whole harness rests on. Three steps:
	// PING/PONG, so everything the server sent has been read; settle, so it has
	// been folded into the core's state; PING/PONG again, so anything the core
	// wrote in reaction (the MODE and CHATHISTORY a join provokes) is queued on
	// the server side. The third step is not belt and braces: the v2 core reacts
	// on this goroutine, after the first PONG, so without it "has the client
	// asked for X yet?" would be a race instead of a question with an answer.
	barrier := func() {
		srv.Sync()
		c.settle(t)
		srv.Sync()
	}
	// appendToLast folds a conditional reply's facts into the group of the line
	// that provoked it: a NAMES the client only sent because of a MODE is part
	// of that MODE's consequences, not a step of its own.
	appendToLast := func() {
		if len(run.groups) == 0 {
			add("(reply)")
			return
		}
		last := &run.groups[len(run.groups)-1]
		last.facts = sortFacts(append(last.facts, take()...))
	}

	c.start(t)
	barrier()
	add("registration")

	last := "" // the most recent line the client sent, for %LABEL%
	for i, st := range steps {
		switch st.kind {
		case stepWait:
			last = srv.WaitFor(st.pat)

		case stepSend:
			for _, ln := range st.lines {
				srv.Send(expand(ln, last))
			}
			barrier()
			add(fmt.Sprintf("%d S: %s", i, strings.Join(st.lines, " / ")))

		case stepReply:
			asked := false
			for _, pending := range srv.Pending() {
				if testsrv.Match(st.pat, pending) {
					asked = true
					break
				}
			}
			if !asked {
				continue
			}
			last = srv.WaitFor(st.pat)
			for _, ln := range st.lines {
				srv.Send(expand(ln, last))
			}
			barrier()
			appendToLast()

		case stepAct:
			c.do(t, st.act)
			barrier()
			add(fmt.Sprintf("%d C: %s", i, st.act))

		case stepDrop:
			srv.Close()
			srv.NextConn()
			srv.Register(nick)
			barrier()
			add(fmt.Sprintf("%d reconnect", i))
		}
	}
	run.state = c.snapshot()
	c.stop(t)
	return run
}

// expand substitutes %LABEL% with the label the core under test put on the last
// command it sent. A transcript cannot hardcode one — v1 labels nothing and v2
// generates them — so a scripted echo says "@%LABEL%;msgid=e1 :eco!…" and gets
// "@label=abc;msgid=e1" against v2 and "@msgid=e1" against v1. The tag prefix is
// rebuilt afterwards so the empty case leaves no stray ';' or bare '@'.
func expand(line, lastClientLine string) string {
	if !strings.Contains(line, "%LABEL%") {
		return line
	}
	sub := ""
	if v := tagValue(lastClientLine, "label"); v != "" {
		sub = "label=" + v
	}
	line = strings.ReplaceAll(line, "%LABEL%", sub)
	if !strings.HasPrefix(line, "@") {
		return line
	}
	tags, rest, _ := strings.Cut(line[1:], " ")
	kept := make([]string, 0, 4)
	for _, kv := range strings.Split(tags, ";") {
		if kv != "" {
			kept = append(kept, kv)
		}
	}
	if len(kept) == 0 {
		return rest
	}
	return "@" + strings.Join(kept, ";") + " " + rest
}

// tagValue reads one message tag off a raw line, "" when absent.
func tagValue(line, tag string) string {
	if !strings.HasPrefix(line, "@") {
		return ""
	}
	tags, _, _ := strings.Cut(line[1:], " ")
	for _, kv := range strings.Split(tags, ";") {
		k, v, _ := strings.Cut(kv, "=")
		if k == tag {
			return v
		}
	}
	return ""
}

// waitUntil polls a condition, failing the test if it never holds. It is used
// only for teardown, where the v1 Session offers no channel to wait on from
// outside its package.
func waitUntil(t *testing.T, what string, d time.Duration, ok func() bool) {
	t.Helper()
	deadline := time.Now().Add(d)
	for !ok() {
		if time.Now().After(deadline) {
			t.Errorf("timed out after %v waiting for %s", d, what)
			return
		}
		time.Sleep(time.Millisecond)
	}
}

// memberLine renders one member for a snapshot.
func memberLine(nick, prefixes string) string {
	if prefixes == "" {
		return strings.ToLower(nick)
	}
	return strings.ToLower(nick) + "(" + prefixes + ")"
}

// lineFacts renders a v1 buffer's log.
func lineFacts(name string, lines []model.Line) []Fact {
	out := make([]Fact, 0, len(lines))
	for _, l := range lines {
		out = append(out, factFromLine(name, l))
	}
	return out
}
